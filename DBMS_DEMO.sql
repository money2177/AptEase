-- 1. Correlated nested query: find apartments with overdue unpaid bills.
SELECT u.block,u.number FROM units u
WHERE EXISTS (SELECT 1 FROM bill_balances b
              WHERE b.unit_id=u.id AND b.due_date<CURRENT_DATE AND b.balance>0)
ORDER BY u.block,u.number;

-- 2. CTE: total outstanding balances by block, including zero-balance blocks.
WITH unit_balances AS (
  SELECT u.id,u.block,COALESCE(SUM(b.balance),0) AS balance
  FROM units u LEFT JOIN bill_balances b ON b.unit_id=u.id GROUP BY u.id
)
SELECT block,SUM(balance)/100.0 AS outstanding_rupees
FROM unit_balances GROUP BY block ORDER BY block;

-- 3. Recursive CTE: create a six-month calendar and report bills even in empty months.
WITH RECURSIVE months(month_start,n) AS (
  SELECT date_trunc('month',CURRENT_DATE)::date,1
  UNION ALL
  SELECT (month_start-INTERVAL '1 month')::date,n+1 FROM months WHERE n<6
)
SELECT m.month_start,COUNT(b.id) AS bills_issued,COALESCE(SUM(b.amount),0)/100.0 AS billed_rupees
FROM months m LEFT JOIN bills b ON b.period=to_char(m.month_start,'YYYY-MM')
GROUP BY m.month_start ORDER BY m.month_start;

-- 4. Window functions: rank unpaid bills per apartment and compute its running balance.
SELECT unit_id,period,balance,
       DENSE_RANK() OVER (PARTITION BY unit_id ORDER BY balance DESC) AS debt_rank,
       SUM(balance) OVER (PARTITION BY unit_id ORDER BY period ROWS UNBOUNDED PRECEDING) AS running_paise
FROM bill_balances WHERE balance>0 ORDER BY unit_id,period;

-- 5. Full-text search: find and rank complaints about music or rubbish.
WITH documents AS (
  SELECT id,subject,to_tsvector('english',subject || ' ' || description) AS document FROM complaints
)
SELECT id,subject,ts_rank(document,to_tsquery('english','music | rubbish')) AS rank
FROM documents WHERE document @@ to_tsquery('english','music | rubbish') ORDER BY rank DESC,id;

