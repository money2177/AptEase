-- DDL: tables, keys, indexes and balance view.
CREATE TABLE units (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, block TEXT NOT NULL, number TEXT NOT NULL,
 bedrooms INTEGER NOT NULL CHECK(bedrooms BETWEEN 1 AND 8), UNIQUE(block,number)
);
CREATE TABLE users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, username TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','resident','guard'))
);
CREATE TABLE occupancies (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, unit_id INTEGER NOT NULL REFERENCES units(id),
 user_id INTEGER NOT NULL REFERENCES users(id), kind TEXT NOT NULL CHECK(kind IN ('Owner','Tenant')),
 start_date DATE NOT NULL, end_date DATE CHECK(end_date >= start_date)
);
CREATE UNIQUE INDEX one_current_home ON occupancies(user_id) WHERE end_date IS NULL;
CREATE INDEX occupancy_unit ON occupancies(unit_id,end_date);
CREATE TABLE resident_registrations (
 user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 request_id TEXT NOT NULL UNIQUE,
 unit_id INTEGER NOT NULL REFERENCES units(id),
 kind TEXT NOT NULL CHECK(kind IN ('Owner','Tenant')),
 requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE bills (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, unit_id INTEGER NOT NULL REFERENCES units(id),
 period TEXT NOT NULL, amount INTEGER NOT NULL CHECK(amount > 0), due_date DATE NOT NULL,
 UNIQUE(unit_id,period)
);
CREATE TABLE payments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, bill_id INTEGER NOT NULL REFERENCES bills(id),
 amount INTEGER NOT NULL CHECK(amount > 0), reference TEXT NOT NULL UNIQUE,
 paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX payments_bill ON payments(bill_id);
CREATE VIEW bill_balances AS
 SELECT b.*, COALESCE(SUM(p.amount),0) AS paid, b.amount-COALESCE(SUM(p.amount),0) AS balance
 FROM bills b LEFT JOIN payments p ON p.bill_id=b.id GROUP BY b.id;
CREATE TABLE tickets (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, occupancy_id INTEGER NOT NULL REFERENCES occupancies(id),
 subject TEXT NOT NULL, description TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'Open' CHECK(status IN ('Open','In progress','Resolved')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE visits (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, unit_id INTEGER NOT NULL REFERENCES units(id),
 visitor TEXT NOT NULL, purpose TEXT NOT NULL, arrived_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 departed_at TIMESTAMPTZ
);
CREATE TABLE visit_requests (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reference TEXT NOT NULL UNIQUE,
 unit_id INTEGER NOT NULL REFERENCES units(id),
 visitor TEXT NOT NULL, purpose TEXT NOT NULL, visit_date DATE NOT NULL,
 decision TEXT NOT NULL DEFAULT 'Pending' CHECK(decision IN ('Pending','Approved','Declined')),
 decided_by INTEGER REFERENCES occupancies(id),
 visit_id INTEGER UNIQUE REFERENCES visits(id)
);
CREATE INDEX visit_requests_unit ON visit_requests(unit_id,visit_date);
CREATE TABLE complaints (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, occupancy_id INTEGER NOT NULL REFERENCES occupancies(id),
 category TEXT NOT NULL CHECK(category IN ('Noise','Cleanliness','Security','Shared spaces','Other')),
 subject TEXT NOT NULL, description TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'Open' CHECK(status IN ('Open','In progress','Resolved')),
 response TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX complaints_occupancy ON complaints(occupancy_id);
CREATE TABLE notices (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL, body TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE parking (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slot TEXT NOT NULL UNIQUE,
 unit_id INTEGER REFERENCES units(id), vehicle TEXT UNIQUE,
 CHECK((unit_id IS NULL) = (vehicle IS NULL))
);
CREATE TABLE facilities (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE
);
CREATE TABLE bookings (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, facility_id INTEGER NOT NULL REFERENCES facilities(id),
 occupancy_id INTEGER NOT NULL REFERENCES occupancies(id),
 day DATE NOT NULL, hour INTEGER NOT NULL CHECK(hour BETWEEN 8 AND 20),
 UNIQUE(facility_id,day,hour)
);

-- Stored SQL function: return the outstanding balance for a bill in paise.
CREATE FUNCTION bill_outstanding(p_bill_id integer) RETURNS bigint
LANGUAGE sql STABLE SET search_path = aptease_demo, pg_catalog
AS $$ SELECT balance FROM bill_balances WHERE id = p_bill_id $$;

-- Trigger: serialize payment writes against the same bill before reading its ledger.
CREATE FUNCTION check_payment_balance() RETURNS trigger
LANGUAGE plpgsql SET search_path = aptease_demo, pg_catalog AS $$
DECLARE
  billed integer;
  already_paid bigint;
  previous_id integer;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    previous_id := OLD.id;
  END IF;
  UPDATE bills SET amount = amount WHERE id = NEW.bill_id RETURNING amount INTO billed;
  SELECT COALESCE(SUM(amount), 0) INTO already_paid FROM payments
    WHERE bill_id = NEW.bill_id AND id IS DISTINCT FROM previous_id;
  IF already_paid + NEW.amount > billed THEN
    RAISE EXCEPTION 'Payment exceeds outstanding balance' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER prevent_overpayment BEFORE INSERT OR UPDATE OF amount, bill_id ON payments
FOR EACH ROW EXECUTE FUNCTION check_payment_balance();

